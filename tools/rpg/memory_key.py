#!/usr/bin/env python3
"""Draws textures/item/memory_key.png, the 32 x 32 Memory Key.

The pixel map below is the source: one character per pixel, in the item palette
of chronicle_shard / recalled_hour (ink outline, a six-step bronze ramp and the
teal crystal ramp). Edit the map and rerun.
Run from the repository root:

    python3 tools/rpg/memory_key.py
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'shared/common/src/main/resources/assets/tbos/textures/item/memory_key.png'

PALETTE = {
    '.': None,
    'O': '#0d0b14',
    '1': '#3a2716', '2': '#5e4024', '3': '#8a6033', '4': '#be8b4a', '5': '#e8c07a', '6': '#ffe29b',
    'a': '#103a42', 'b': '#1f6e74', 'c': '#3fb0ac', 'd': '#9cf2e6', 'e': '#d7fff7',
}
MAP = """
................................
................................
................................
........................OOO.....
.......................OO64O....
......................OO6442O...
.....................OO6442OOOO.
....................OO64425554O.
...................OO644244332O.
..................OO6442322222O.
.................OO6442OOOOOOOO.
................OO64425554O.....
...............OO644243322O.....
..............OO6442OOOOOOO.....
......OOOOOOOOO6442OO...........
....OOO6665OO66442OO............
...OO666665555542OO.............
..OO666233354453OO..............
.OO66222OO344443O...............
.O6662OOddOO4433O...............
.O662OOdeccOO533O...............
.O663OdecccbO533O...............
.O663decccbbb522O...............
.O553OdccbbbO522O...............
.O553OOcbbbOO622O...............
.O5544OObbOO6222O...............
.OO44445OO66622OO...............
..OO4435556222OO................
...OO33322222OO.................
....OOO3222OOO..................
......OOOOOO....................
................................
"""


def main():
    rows = MAP.strip('\n').split('\n')
    assert len(rows) == 32 and all(len(r) == 32 for r in rows), 'the map must be 32 x 32'
    img = Image.new('RGBA', (32, 32), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            c = PALETTE[ch]
            if c:
                img.putpixel((x, y), tuple(int(c[i:i + 2], 16) for i in (1, 3, 5)) + (255,))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    img.save(OUT)
    print(f'wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
